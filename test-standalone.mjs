import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { Script } from 'node:vm';
import { dashboard } from './dist/dashboard.mjs';
import { units, vendors, transactions } from './dist/data.mjs';
import { filterRows, summarize, priorYearRows } from './dist/analytics.mjs';
const html=await readFile(new URL('./index.html',import.meta.url),'utf8');
const inline=html.match(/<script id="overarch-app">\n([\s\S]*?)\n<\/script>/)?.[1];
assert.ok(inline,'The standalone app must contain its executable script.');
new Script(inline);
assert.ok(!/<script[^>]+\bsrc=|<link[^>]+rel="stylesheet"|@import\s|\bsrc="\.\//i.test(html));
assert.ok(html.includes("'S$'"),'Dollar signs must survive replacement-string handling.');
assert.ok(html.includes('amount_sgd'));
assert.ok(html.includes('name: \'PAC\''));
const filters={period:'2026',unit:'all',category:'all',month:'all',supplier:'all',search:''};
const rows=filterRows(transactions,filters),s=summarize(rows,units,vendors);
const rendered=dashboard(s,rows,{filters,units,trendRows:rows,previousRows:priorYearRows(transactions,filters),comparisonRows:priorYearRows(transactions,filters),trendMode:'monthly',compareEnabled:true,scenarioRate:5,demo:true});
assert.ok(rendered.includes('S$12.48m'));
assert.ok(rendered.includes('PAC')&&rendered.includes('PS')&&rendered.includes('ES'));
assert.ok(!/world-map|global footprint|continents/.test(rendered));
assert.ok(rendered.includes('6<span>category signals'));
console.log('Standalone HTML and composed Singapore dashboard checks passed.');
