import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Script } from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = name => readFile(path.join(root, name), 'utf8');
const moduleNames = ['data', 'utilities', 'analytics', 'world-land', 'dashboard', 'app'];
const modules = [];
for (const name of moduleNames) {
  let source = await read(`dist/${name}.mjs`);
  const exports = [...source.matchAll(/^export\s+(?:const|let|function|class)\s+([\w$]+)/gm)].map(match => match[1]);
  source = source.replace(/^import\s+\{([^}]+)\}\s+from\s+['"]\.\/([^?'"/]+)\.mjs(?:\?[^'"]*)?['"];\s*$/gm, (_, names, dependency) => {
    if (!moduleNames.includes(dependency)) throw Error(`Unknown dependency: ${dependency}`);
    const bindings = names.split(',').map(name => name.trim().replace(/\s+as\s+/, ': ')).join(', ');
    return `const { ${bindings} } = __overarch[${JSON.stringify(dependency)}];`;
  }).replace(/^export\s+/gm, '');
  if (/^\s*(?:import|export)\s/m.test(source)) throw Error(`Unbundled module declaration in ${name}`);
  modules.push(`__overarch[${JSON.stringify(name)}] = (() => {\n${source}\nreturn { ${exports.join(', ')} };\n})();`);
}
const javascript = `'use strict';\n(() => {\nconst __overarch = Object.create(null);\n${modules.join('\n\n')}\n})();`;
new Script(javascript, { filename: 'OverArch-inline.js' });

const fontFaces = [];
const licenses = {};
for (const [filename, family, weights] of [['dm-sans', 'DM Sans', '400 700'], ['manrope', 'Manrope', '400 800']]) {
  const bytes = await readFile(path.join(root, `assets/fonts/${filename}.woff2`));
  fontFaces.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:${weights};font-display:swap;src:url(data:font/woff2;base64,${bytes.toString('base64')}) format('woff2')}`);
  licenses[family] = await read(`assets/fonts/${filename}-OFL.txt`);
}
const css = [fontFaces.join('\n'), (await read('dist/styles.css')).replace(/^@import[^\n]+\n/gm, ''), await read('dist/theme.css')].join('\n');
const logo = 'data:image/svg+xml;base64,' + Buffer.from(await read('dist/logo-mark.svg')).toString('base64');
let html = await read('dist/index.html');
html = html.replace(/\s*<link rel="stylesheet"[^>]*>/g, '').replace(/\s*<script type="module"[^>]*><\/script>/g, '');
html = html.replace(/\.\/logo-mark\.svg(?:\?[^"']*)?/g, logo);
html = html.replace('</head>', `<style>\n${css}\n</style>\n</head>`);
const escapeScript = text => text.replace(/<\/script/gi, '<\\/script');
html = html.replace('</body>', `<script type="application/json" id="font-licenses">${escapeScript(JSON.stringify(licenses))}</script>\n<script id="overarch-app">\n${escapeScript(javascript)}\n</script>\n</body>`);
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- OverArch standalone app. Generated by node scripts/build-html.mjs. Fonts: SIL OFL 1.1; licenses embedded below. Map: Natural Earth public-domain geometry. -->');
if (/<script[^>]+\bsrc\s*=|<link[^>]+rel="stylesheet"|@import\s|\bsrc="\.\//i.test(html)) throw Error('An external runtime asset remains.');
await writeFile(path.join(root, 'index.html'), html);
console.log(`Built standalone index.html (${(Buffer.byteLength(html) / 1024).toFixed(1)} KB).`);
